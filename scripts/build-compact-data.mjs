import fs from 'fs';
import path from 'path';

const INPUT_ALIASES = path.join(process.cwd(), 'data/aliases/drugs.json');
const OUTPUT_PUBLIC_DIR = path.join(process.cwd(), 'public/data');
const OUTPUT_COMPACT_JSON = path.join(OUTPUT_PUBLIC_DIR, 'drugs.compact.json');
const OUTPUT_BASELINE_TS = path.join(process.cwd(), 'lib/baseline_aliases.ts');

async function buildCompactData() {
  console.log('Compiling compact index for NutriDive SafeStack...');

  if (!fs.existsSync(INPUT_ALIASES)) {
    console.error(`Aliases file not found at: ${INPUT_ALIASES}`);
    process.exit(1);
  }

  if (!fs.existsSync(OUTPUT_PUBLIC_DIR)) {
    fs.mkdirSync(OUTPUT_PUBLIC_DIR, { recursive: true });
  }

  const rawAliases = JSON.parse(fs.readFileSync(INPUT_ALIASES, 'utf-8'));
  console.log(`Loaded ${rawAliases.length} aliases.`);

  // 1. Build class dictionary
  const classList = [];
  const classIndexMap = new Map();

  rawAliases.forEach(item => {
    if (!classIndexMap.has(item.classId)) {
      classIndexMap.set(item.classId, classList.length);
      classList.push(item.classId);
    }
  });

  // 2. Encode as compact tuples [keyword, classIdx, displayName]
  const compactEntries = rawAliases.map(item => [
    item.keyword,
    classIndexMap.get(item.classId),
    item.name
  ]);

  const compactPayload = {
    c: classList,
    d: compactEntries
  };

  const compactJsonString = JSON.stringify(compactPayload);
  fs.writeFileSync(OUTPUT_COMPACT_JSON, compactJsonString, 'utf-8');

  const origSizeMb = (fs.statSync(INPUT_ALIASES).size / (1024 * 1024)).toFixed(2);
  const compactSizeMb = (Buffer.byteLength(compactJsonString) / (1024 * 1024)).toFixed(2);

  console.log(`Original JSON size: ${origSizeMb} MB`);
  console.log(`Compact JSON size: ${compactSizeMb} MB (saved ~${((1 - compactSizeMb / origSizeMb) * 100).toFixed(1)}%)`);
  console.log(`Saved to: ${OUTPUT_COMPACT_JSON}`);

  // 3. Extract Curated High-Priority Baseline for Instant Offline/SSR Execution
  // Includes all foods, key herbs, vitamins, minerals, and common chronic disease medications
  const isPriority = (item) => {
    const k = item.keyword.toLowerCase();
    const c = item.classId.toLowerCase();
    return (
      c.startsWith('food_') ||
      c.startsWith('supp_') ||
      c.startsWith('mineral_') ||
      c.startsWith('herb_') ||
      c.startsWith('vitamin_') ||
      c.includes('statin') ||
      c.includes('metformin') ||
      c.includes('levothyroxine') ||
      c.includes('warfarin') ||
      c.includes('ace_inhibitor') ||
      c.includes('ppi_') ||
      c.includes('fluoroquinolone') ||
      c.includes('tetracycline') ||
      c.includes('bisphosphonate') ||
      c.includes('corticosteroid') ||
      c.includes('diuretic') ||
      c.includes('phosphodiesterase') ||
      k === 'lipitor' ||
      k === 'norvasc' ||
      k === 'coumadin' ||
      k === 'glucophage' ||
      k === 'synthroid' ||
      k === 'ciprofloxacin' ||
      k === 'prednisone' ||
      k === 'omeprazole' ||
      k === 'alendronate' ||
      k === 'spironolactone' ||
      k === 'aspirin' ||
      k === 'ibuprofen'
    );
  };

  const priorityAliases = rawAliases.filter(isPriority);
  console.log(`Selected ${priorityAliases.length} high-priority baseline aliases for instant SSR loading.`);

  const baselineCode = `// Autogenerated instant baseline for SSR & offline fast boot
export interface CompactAlias {
  keyword: string;
  classId: string;
  name: string;
}

export const BASELINE_ALIASES: CompactAlias[] = ${JSON.stringify(priorityAliases, null, 2)};
`;

  fs.writeFileSync(OUTPUT_BASELINE_TS, baselineCode, 'utf-8');
  console.log(`Generated synchronous baseline in: ${OUTPUT_BASELINE_TS}`);
}

buildCompactData();
